#!/usr/bin/env python3
import os
import sys
import time
import subprocess
import ldap
import ldap.sasl
from ldap.controls.psearch import PersistentSearchControl

IPA_SERVER = "ldap://test.usb.guar"
BASE_DN = "dc=usb,dc=guar"
CUSTOM_ATTR = "usbguardrules"
RULES_FILE = "/etc/usbguard/rules.conf" 

def kinit_host():
    try:
        hostname = subprocess.check_output(["hostname", "-f"]).decode().strip()
        principal = f"host/{hostname}"
        subprocess.run(["kinit", "-k", "-t", "/etc/krb5.keytab", principal], check=True)
    except Exception as e:
        print(f"[{time.strftime('%T')}] Ошибка Kerberos kinit: {e}", file=sys.stderr)

def fetch_and_apply_rules(con):
    try:
        hostname = subprocess.check_output(["hostname", "-f"]).decode().strip()
        host_dn = f"fqdn={hostname},cn=computers,cn=accounts,{BASE_DN}"
        search_filter = f"(&(objectClass=ipahostgroup)(|(member={host_dn})(member={hostname})))"

        result = con.search_s(f"cn=hostgroups,cn=accounts,{BASE_DN}", ldap.SCOPE_SUBTREE, search_filter, [CUSTOM_ATTR])

        rules = []
        for dn, attrs in result:
            if CUSTOM_ATTR in attrs:
                for rule in attrs[CUSTOM_ATTR]:
                    raw_text = rule.decode('utf-8')
                    formatted = raw_text.replace(" allow", "\nallow").replace(" block", "\nblock")
                    for line in formatted.split("\n"):
                        line = line.strip()
                        if line:
                            rules.append(line)

        new_config = f"# Generated by FreeIPA Real-time Daemon\n# DO NOT EDIT MANUALLY\n"
        if rules:
            new_config += "\n".join(rules) + "\n"
        else:
            new_config += "allow with-interface match-all\n"

        if os.path.exists(RULES_FILE):
            with open(RULES_FILE, "r") as f:
                if f.read() == new_config:
                    return
            subprocess.run(["chattr", "-i", RULES_FILE], check=False)

        print(f"[{time.strftime('%T')}] Обнаружены изменения во FreeIPA. Обновляем локальные правила...")

        with open(RULES_FILE, "w") as f:
            f.write(new_config)

        os.chmod(RULES_FILE, 0o600)
        subprocess.run(["chattr", "+i", RULES_FILE], check=True)
        subprocess.run(["systemctl", "restart", "usbguard"], check=True)
        print(f"[{time.strftime('%T')}] Правила успешно обновлены и заблокированы флагом immutable.")

    except Exception as e:
        print(f"[{time.strftime('%T')}] Ошибка при обновлении конфигурации: {e}", file=sys.stderr)

def main():
    kinit_host()
    while True:
        try:
            ldap.set_option(ldap.OPT_X_TLS_REQUIRE_CERT, ldap.OPT_X_TLS_ALLOW)
            con = ldap.initialize(IPA_SERVER)
            con.protocol_version = ldap.VERSION3

            auth = ldap.sasl.gssapi("")
            con.sasl_interactive_bind_s("", auth)

            fetch_and_apply_rules(con)

            psc = PersistentSearchControl(changeTypes=15, changesOnly=True, returnECs=True)
            msg_id = con.search_ext(
                f"cn=hostgroups,cn=accounts,{BASE_DN}",
                ldap.SCOPE_SUBTREE,
                f"(objectClass=ipahostgroup)",
                attrlist=['cn'],
                serverctrls=[psc]
            )

            print(f"[{time.strftime('%T')}] Подключение установлено. Демон в режиме ожидания изменений...")

            while True:
                res_type, res_data, res_msgid, _ = con.result2(msg_id, all=0, timeout=None)
                if res_data:
                    kinit_host()
                    fetch_and_apply_rules(con)

        except (ldap.SERVER_DOWN, ldap.CONNECT_ERROR, ldap.TIMEOUT):
            print(f"[{time.strftime('%T')}] Связь с FreeIPA потеряна. Повторная попытка через 15 секунд...")
            time.sleep(15)
            kinit_host()
        except Exception as e:
            print(f"[{time.strftime('%T')}] Непредвиденная ошибка: {e}. Перезапуск цикла через 15 секунд...")
            time.sleep(15)

if __name__ == "__main__":
    main()
